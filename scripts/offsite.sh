#!/usr/bin/env bash
# Encrypted off-site copies of local backups with restic (run in the
# restic/restic container; nothing to install).
#
#   offsite.sh push [backups/<stamp>]  upload a local backup (default: newest), then apply retention
#   offsite.sh snapshots               list off-site snapshots
#   offsite.sh check                   verify the repository's integrity
#   offsite.sh restore [snapshot]      download a snapshot (default: latest) into backups/
#
# Configure in .env: RESTIC_REPOSITORY (empty = off-site disabled), plus
# backend credentials if needed. The encryption password is generated by
# bootstrap in secrets/restic_password. KEEP A COPY OF IT SOMEWHERE ELSE:
# without it the off-site backups cannot be decrypted.
set -euo pipefail
source "$(dirname "$0")/lib.sh"

require_env
BACKUP_DIR="${BACKUP_DIR:-backups}"
RESTIC_IMAGE="restic/restic:${RESTIC_VERSION:-0.20.0}"
OFFSITE_KEEP="${OFFSITE_KEEP:---keep-daily 7 --keep-weekly 4 --keep-monthly 6}"
MARKER="$BACKUP_DIR/.offsite-last"

[[ -n "${RESTIC_REPOSITORY:-}" ]] || die "Off-site backups are disabled: set RESTIC_REPOSITORY in $ENV_FILE"
[[ -s "$SECRETS_DIR/restic_password" ]] || die "$SECRETS_DIR/restic_password missing. Run: make bootstrap"
mkdir -p "$BACKUP_DIR"

# Run restic in its container as the current user. Backend credentials from
# .env are passed through only when set.
restic() {
  local args=(
    --rm -i --user "$(id -u):$(id -g)"
    -e RESTIC_REPOSITORY -e RESTIC_PASSWORD_FILE=/run/secrets/restic_password
    -e RESTIC_CACHE_DIR=/cache -e HOME=/tmp
    -v "$REPO_ROOT/$SECRETS_DIR/restic_password:/run/secrets/restic_password:ro"
    -v "$REPO_ROOT/$BACKUP_DIR:/backups"
    -v "$cache_dir:/cache"
  )
  local var
  for var in AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY AWS_DEFAULT_REGION \
             B2_ACCOUNT_ID B2_ACCOUNT_KEY RESTIC_REST_USERNAME RESTIC_REST_PASSWORD; do
    [[ -n "${!var:-}" ]] && args+=(-e "$var")
  done
  # A local path (e.g. a mounted NAS share) is mounted at the same path.
  if [[ "$RESTIC_REPOSITORY" == /* ]]; then
    mkdir -p "$RESTIC_REPOSITORY"
    args+=(-v "$RESTIC_REPOSITORY:$RESTIC_REPOSITORY")
  fi
  docker run "${args[@]}" "$RESTIC_IMAGE" "$@"
}

cache_dir="${XDG_CACHE_HOME:-$HOME/.cache}/gitea-lab-restic"
mkdir -p "$cache_dir"

ensure_repo() {
  if ! restic cat config >/dev/null 2>&1; then
    info "Initialising restic repository $RESTIC_REPOSITORY"
    restic init >/dev/null
    pass "Repository created (password: $SECRETS_DIR/restic_password — keep a copy off this machine)"
  fi
}

latest_local() {
  find "$BACKUP_DIR" -mindepth 1 -maxdepth 1 -type d -regextype posix-extended \
    -regex '.*/[0-9]{8}-[0-9]{6}' 2>/dev/null | sort | tail -n1 || true
}

cmd="${1:-}"
case "$cmd" in
  push)
    src="${2:-$(latest_local)}"
    [[ -d "$src" ]] || die "No local backup to upload (run: make backup)"
    stamp="$(basename "$src")"
    ensure_repo
    info "Uploading $stamp to $RESTIC_REPOSITORY"
    restic backup --quiet --host "$(lab_name)" --tag "$stamp" "/backups/$stamp"
    pass "Off-site snapshot of $stamp created"
    # shellcheck disable=SC2086  # OFFSITE_KEEP holds several restic flags
    restic forget --quiet --host "$(lab_name)" --prune $OFFSITE_KEEP
    pass "Retention applied ($OFFSITE_KEEP)"
    date +%s > "$MARKER"
    ;;
  snapshots)
    restic snapshots --host "$(lab_name)"
    ;;
  check)
    restic check
    ;;
  restore)
    snap="${2:-latest}"
    info "Downloading snapshot $snap into $BACKUP_DIR/"
    restic restore "$snap" --host "$(lab_name)" --target /
    pass "Restored. Now run: make restore BACKUP=latest  (or BACKUP=$BACKUP_DIR/<stamp>)"
    ;;
  *)
    die "Usage: $0 push [dir] | snapshots | check | restore [snapshot]"
    ;;
esac
